/// The inventory is shared by navigation, validation and the coverage report.
/// A feature can use several protocol calls without adding duplicate screens.
class NeteaseEndpoint {
  const NeteaseEndpoint({
    required this.route,
    required this.title,
    required this.tab,
    required this.category,
    required this.description,
    required this.parameters,
    required this.write,
    this.unavailable,
  });
  final String route, title, tab, category, description;
  final List<NeteaseParameter> parameters;
  final bool write;
  final String? unavailable;
  factory NeteaseEndpoint.fromJson(Map<String, dynamic> item) =>
      NeteaseEndpoint(
        route: item['route'] as String,
        title: item['title'] as String,
        tab: item['tab'] as String,
        category: item['category'] as String,
        description: item['description'] as String,
        parameters: [
          for (final p in item['params'] as List)
            NeteaseParameter(
              '${p['key']}',
              p['required'] == true,
              '${p['help'] ?? ''}',
            ),
        ],
        write: item['write'] == true,
        unavailable: item['unavailable'] as String?,
      );
}

class NeteaseParameter {
  const NeteaseParameter(this.key, this.required, [this.help = '']);
  final String key, help;
  final bool required;
  String get label => neteaseFieldLabels[key] ?? '其他筛选条件';
  bool get private => {
    'password',
    'md5_password',
    'captcha',
    'oldcaptcha',
    'newcaptcha',
    'token',
    'sign',
  }.contains(key);
  bool get multiline => {
    'content',
    'msg',
    'text',
    'description',
    'reason',
    'ids',
    'tracks',
    'user_ids',
    'randomList',
    'displayList',
  }.contains(key);
}

final neteaseCatalogProvider = FutureProvider<List<NeteaseEndpoint>>((
  ref,
) async {
  final json =
      jsonDecode(
            await rootBundle.loadString(
              'assets/data/netease-full-catalog.json',
            ),
          )
          as Map;
  return List.unmodifiable([
    for (final row in json['entries'] as List)
      NeteaseEndpoint.fromJson(Map<String, dynamic>.from(row)),
  ]);
});

