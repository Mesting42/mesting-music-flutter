import 'package:flutter/foundation.dart';
import 'package:flutter/scheduler.dart';
import 'dart:async';
import 'dart:ui' show FramePhase;
import 'package:liquid_glass_widgets/glass_render_diagnostics.dart';

const bool frameTimingProbeEnabled = bool.fromEnvironment(
  'MESTING_FRAME_TIMING_PROBE',
);

class FrameTimingProbe {
  FrameTimingProbe._();

  static const _sampleSize = 120;
  static final List<FrameTiming> _samples = <FrameTiming>[];
  static bool _started = false;
  static final recording = ValueNotifier(false);
  static final draining = ValueNotifier(false);
  static final List<FrameTiming> _session = [];
  static final List<Map<String, Object>> _transitions = [];
  static Timer? _deadline;
  static double _displayHz = 0;
  static final _elapsed = Stopwatch();
  static bool _frameObserverInstalled = false;
  static int _startVsyncUs = 0;
  static int? _stopVsyncUs;
  static int _stopElapsedUs = 0;
  static Completer<void>? _stopCompleter;
  static final List<Map<String, int>> _clockAnchors = [];
  static Map<String, Object> _environment = {};

  /// Opt-in on-device capture. It records timing categories only: no songs,
  /// account IDs, credentials, network responses or filesystem paths.
  static void beginSession(
    double displayHz, {
    Map<String, Object> environment = const {},
  }) {
    if (draining.value) return;
    _deadline?.cancel();
    _session.clear();
    _transitions.clear();
    _clockAnchors.clear();
    _environment = Map.of(environment);
    _displayHz = displayHz;
    _startVsyncUs =
        SchedulerBinding.instance.currentSystemFrameTimeStamp.inMicroseconds;
    _stopVsyncUs = null;
    _stopElapsedUs = 0;
    _stopCompleter = null;
    _elapsed
      ..reset()
      ..start();
    _listen();
    if (!_frameObserverInstalled) {
      // Passive observer: never requests a frame or installs a diagnostic ticker.
      // Raw engine vsync anchors match FrameTiming, unlike the animation epoch.
      SchedulerBinding.instance.addPersistentFrameCallback(_observeFrame);
      _frameObserverInstalled = true;
    }
    GlassRenderDiagnostics.begin(afterVsyncUs: _startVsyncUs);
    recording.value = true;
    _deadline = Timer(
      const Duration(seconds: 90),
      () => unawaited(stopSession()),
    );
  }

  static void markTransition(String label) {
    if (!recording.value || _transitions.length >= 250) return;
    _transitions.add({
      'event': label,
      'elapsedMs': _elapsed.elapsedMilliseconds,
      'elapsedUs': _elapsed.elapsedMicroseconds,
      // A gesture may occur between frames. Keep its preceding and following
      // raw vsync rather than inventing an exact GPU/presentation timestamp.
      'lastVsyncUs':
          SchedulerBinding.instance.currentSystemFrameTimeStamp.inMicroseconds,
    });
  }

  static void _observeFrame(Duration _) {
    if (!recording.value) return;
    final vsync =
        SchedulerBinding.instance.currentSystemFrameTimeStamp.inMicroseconds;
    if (_clockAnchors.length < 14000) {
      _clockAnchors.add({
        'vsyncUs': vsync,
        'elapsedUs': _elapsed.elapsedMicroseconds,
      });
    }
    for (final event in _transitions.reversed) {
      if (event.containsKey('nextVsyncUs')) break;
      if (vsync > (event['lastVsyncUs']! as int)) event['nextVsyncUs'] = vsync;
    }
  }

  /// Release batches timing callbacks roughly once per second. Stop the paint
  /// counters/events now, but retain the callback for 1.2s to drain that batch.
  /// Samples outside the raw engine capture interval are discarded, including
  /// frames queued before Begin or generated by this page after Stop.
  static Future<void> stopSession() {
    if (_stopCompleter != null) return _stopCompleter!.future;
    if (!recording.value) return Future.value();
    final completer = _stopCompleter = Completer<void>();
    _deadline?.cancel();
    _stopVsyncUs =
        SchedulerBinding.instance.currentSystemFrameTimeStamp.inMicroseconds;
    _stopElapsedUs = _elapsed.elapsedMicroseconds;
    GlassRenderDiagnostics.stop();
    draining.value = true;
    recording.value = false;
    _deadline = Timer(const Duration(milliseconds: 1200), () {
      _deadline = null;
      _elapsed.stop();
      if (_started && !frameTimingProbeEnabled) {
        SchedulerBinding.instance.removeTimingsCallback(_collect);
        _started = false;
      }
      draining.value = false;
      completer.complete();
    });
    return completer.future;
  }

  static Map<String, Object> sessionReport() => {
    'schema': 2,
    'displayHz': _displayHz,
    'environment': Map.of(_environment),
    'elapsedMs':
        (_stopElapsedUs == 0 ? _elapsed.elapsedMicroseconds : _stopElapsedUs) ~/
        1000,
    'startVsyncUs': _startVsyncUs,
    'stopVsyncUs': ?_stopVsyncUs,
    'timingsDrained': !draining.value && !recording.value,
    'clockAnchors': [for (final anchor in _clockAnchors) Map.of(anchor)],
    'paintCounters': GlassRenderDiagnostics.report(),
    'summary': frameTimingSummary(_session),
    'events': [for (final event in _transitions) Map.of(event)],
    'samples': [
      for (final timing in _session)
        {
          'vsyncUs': timing.timestampInMicroseconds(FramePhase.vsyncStart),
          'buildUs': timing.buildDuration.inMicroseconds,
          'rasterUs': timing.rasterDuration.inMicroseconds,
          'totalUs': timing.totalSpan.inMicroseconds,
        },
    ],
  };

  static void _listen() {
    if (_started) return;
    _started = true;
    SchedulerBinding.instance.addTimingsCallback(_collect);
  }

  static void start() {
    if (frameTimingProbeEnabled) _listen();
  }

  static void _collect(List<FrameTiming> timings) {
    if (recording.value || draining.value) {
      // Bounded even on 144 Hz displays. Capture preserves real build/raster
      // durations; a widget-test pump count is never reported as device FPS.
      _session.addAll(
        timings
            .where((timing) {
              final vsync = timing.timestampInMicroseconds(
                FramePhase.vsyncStart,
              );
              return vsync > _startVsyncUs &&
                  (_stopVsyncUs == null || vsync <= _stopVsyncUs!);
            })
            .take((14000 - _session.length).clamp(0, 14000)),
      );
    }
    if (!frameTimingProbeEnabled) return;
    _samples.addAll(timings);
    while (_samples.length >= _sampleSize) {
      final sample = _samples.sublist(0, _sampleSize);
      _samples.removeRange(0, _sampleSize);
      debugPrint('MESTING_FRAME_TIMING ${frameTimingSummary(sample)}');
    }
  }

  @visibleForTesting
  static void collectForTest(List<FrameTiming> timings) => _collect(timings);
}

String frameTimingSummary(List<FrameTiming> timings) {
  final builds =
      timings
          .map((timing) => timing.buildDuration.inMicroseconds)
          .toList(growable: false)
        ..sort();
  final rasters =
      timings
          .map((timing) => timing.rasterDuration.inMicroseconds)
          .toList(growable: false)
        ..sort();
  const highRefreshBudgetMicros = 8333;
  const standardRefreshBudgetMicros = 16667;
  final rasterOverHighRefresh = rasters
      .where((duration) => duration > highRefreshBudgetMicros)
      .length;
  final rasterOverStandardRefresh = rasters
      .where((duration) => duration > standardRefreshBudgetMicros)
      .length;

  return <String>[
    'frames=${timings.length}',
    'build_p50_ms=${_percentileMillis(builds, .50)}',
    'build_p90_ms=${_percentileMillis(builds, .90)}',
    'build_p99_ms=${_percentileMillis(builds, .99)}',
    'build_over_8_33=${builds.where((duration) => duration > highRefreshBudgetMicros).length}',
    'raster_p50_ms=${_percentileMillis(rasters, .50)}',
    'raster_p90_ms=${_percentileMillis(rasters, .90)}',
    'raster_p99_ms=${_percentileMillis(rasters, .99)}',
    'raster_over_8_33=$rasterOverHighRefresh',
    'raster_over_16_67=$rasterOverStandardRefresh',
  ].join(' ');
}

String _percentileMillis(List<int> sortedMicros, double percentile) {
  if (sortedMicros.isEmpty) return '0.00';
  final index = ((sortedMicros.length - 1) * percentile).floor();
  return (sortedMicros[index] / 1000).toStringAsFixed(2);
}
